"""Telling the text Claude Code writes into a user turn from the words the person wrote.

The shapes are the ones Claude Code sends, with invented words: a skill command and
its expansion, local commands with their caveat and output, a finished background
task, and the person's typed message merged after them. Crediting the client's text to
the person files a skill's rules or a command's output as the person's decisions;
crediting the person's text to the client loses their decisions. Both are tested.
"""

from hypothesis import given
from hypothesis import strategies as st

from llm_gc.proxy.client_written import client_written_ranges

CAVEAT = ("<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. "
          "DO NOT respond to these messages unless the user explicitly asks you to.</local-command-caveat>")
SKILL = ("<command-message>project-audit is running…</command-message>\n<command-name>/project-audit</command-name>\n"
         "<command-args>verify the report</command-args>")
LOCAL = "<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>"
OUTPUT = "<local-command-stdout>Set model to Sonnet</local-command-stdout>"
EXPANSION = "Base directory for this skill: /skills/audit\n\nReports go under doc/audits/. Keep at most 5 rows."
NOTICE = ("<task-notification>\n<task-id>b6m52</task-id>\n<status>completed</status>\n"
          "<summary>Background command finished</summary>\nThe tests passed.\n</task-notification>")
TYPED = "Let's use Postgres for the ingest service."


def _written(text: str) -> list[str]:
    return [text[start:end].strip() for start, end in client_written_ranges(text)]


class TestWhatTheClientWrote:
    def test_a_skill_commands_expansion_is_the_clients_and_the_command_the_persons(self):
        assert _written(f"{SKILL}\n\n{EXPANSION}") == [EXPANSION]

    def test_a_local_commands_caveat_and_output_are_the_clients_and_the_typed_message_after_them_the_persons(self):
        assert _written(f"{CAVEAT}\n\n{LOCAL}\n\n{OUTPUT}\n\n{TYPED}") == [CAVEAT, OUTPUT]

    def test_a_local_command_that_printed_nothing_expands_to_nothing(self):
        """The caveat says it ran on the person's machine, so the typed words after it are theirs."""
        assert _written(f"{CAVEAT}\n\n{LOCAL}\n\n{TYPED}") == [CAVEAT]

    def test_several_local_commands_before_a_typed_message(self):
        text = f"{CAVEAT}\n\n{LOCAL}\n\n{OUTPUT}\n\n{CAVEAT}\n\n{LOCAL}\n\n{OUTPUT}\n\n{TYPED}"
        assert _written(text) == [CAVEAT, f"{OUTPUT}\n\n{CAVEAT}", OUTPUT]

    def test_a_skill_command_after_a_local_one_still_expands(self):
        assert _written(f"{CAVEAT}\n\n{LOCAL}\n\n{OUTPUT}\n\n{SKILL}\n\n{EXPANSION}") == [CAVEAT, OUTPUT, EXPANSION]

    def test_two_skill_commands_in_one_turn_each_expand(self):
        assert _written(f"{SKILL}\n\n{EXPANSION}\n\n{SKILL}\n\n{EXPANSION}") == [EXPANSION, EXPANSION]

    def test_a_finished_background_task_is_the_clients_whole(self):
        assert _written(NOTICE) == [NOTICE]

    def test_text_the_client_wrote_back_to_back_is_one_range(self):
        assert _written(f"{SKILL}\n\n{EXPANSION}\n\n{NOTICE}") == [f"{EXPANSION}\n\n{NOTICE}"]


class TestWhatStaysThePersons:
    def test_a_turn_with_no_client_elements_is_all_the_persons(self):
        assert client_written_ranges(TYPED) == ()

    def test_an_element_named_in_a_sentence_is_the_person_talking_about_it(self):
        assert client_written_ranges(f"Why does {OUTPUT} show up here?") == ()

    def test_a_command_the_person_pasted_after_their_own_words_expands_to_nothing(self):
        """Claude Code writes a command first in its message; one after the person's words was pasted."""
        assert client_written_ranges(f"Look at this turn:\n{SKILL}\nWhy is it credited to me?") == ()

    def test_the_words_typed_before_a_local_command_stay_the_persons(self):
        assert _written(f"{TYPED}\n\n{CAVEAT}\n\n{LOCAL}\n\n{OUTPUT}\n\nAnd use Redis.") == [CAVEAT, OUTPUT]

    def test_an_unclosed_element_is_not_one(self):
        assert client_written_ranges("<local-command-stdout>half a paste") == ()

    @given(st.text(max_size=300))
    def test_ranges_are_in_order_inside_the_text_and_never_touch(self, text):
        previous_end = -1
        for start, end in client_written_ranges(text):
            assert previous_end < start < end <= len(text)
            previous_end = end
